"""Regenerate the README vector list between its markers from manifest.json.
One idempotent line per entry; a partly covered verified one is axis-scoped."""
from __future__ import annotations

import json
from pathlib import Path

_HERE = Path(__file__).resolve().parent
MANIFEST = _HERE / "conformance-vectors" / "manifest.json"
README = _HERE / "conformance-vectors" / "README.md"
REQUIREMENT_MAP = _HERE / "conformance-vectors" / "requirement-map.json"
#: Prefix of a verified outcome that covers only the axes the map lists.
AXIS_SCOPED_LABEL = "axis-scoped"
_VERIFIED_OUTCOMES = ("verified", "verified_keyed")

START = "<!-- vectors-list:start (regenerated by verifier/render_vector_list.py; do not hand-edit) -->"
END = "<!-- vectors-list:end -->"


def _scope_suffix(vec: dict) -> str:
    """The "n of m requirements" coverage text, empty when none is left out."""
    left_out, covered = len(vec["not_exercised"]), len(vec["exercises"])
    if not left_out:
        return ""
    return f" ({covered} of {covered + left_out} requirements)"


def _render(entries: list[dict]) -> list[str]:
    vectors = json.loads(REQUIREMENT_MAP.read_text(encoding="utf-8"))["vectors"]
    lines = []
    for entry in entries:
        outcome = entry["outcome"]
        suffix = _scope_suffix(vectors[entry["dir"]]) if entry["dir"] in vectors else ""
        if outcome in _VERIFIED_OUTCOMES and suffix:
            outcome = f"{AXIS_SCOPED_LABEL} {outcome}{suffix}"
        if entry.get("reason_code"):
            outcome = f"{outcome} ({entry['reason_code']})"
        lines.append(f"- `{entry['dir']}`: {outcome}")
    return lines


def main() -> int:
    entries = json.loads(MANIFEST.read_text(encoding="utf-8"))
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit("README.md is missing the vectors-list marker comments")
    head, rest = text.split(START, 1)
    _old, tail = rest.split(END, 1)
    body = "\n".join(_render(entries))
    README.write_text(f"{head}{START}\n{body}\n{END}{tail}", encoding="utf-8")
    print(f"rendered {len(entries)} vector lines into {README.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
