#!/usr/bin/env python3
"""Write CODEMAP.md: each source file by folder, with purpose, symbols, tests.
usage: gen_codemap.py [--check]; exit 1 stale under --check, 2 git failure"""

import argparse
import ast
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
OUT = "CODEMAP.md"
SOURCE_PREFIXES = (
    "python/src/", "python/scripts/", "typescript/src/", "verifier/", "tools/", "hooks/",
    "github-action/", "github-action-risk-acceptance/",
)
TEST_PREFIXES = ("tests/", "python/tests/", "typescript/tests/")
CODE_SUFFIXES = {".py", ".js", ".mjs", ".ts", ".sh"}
SYMBOLS_MAX = 15
TESTS_MAX = 3
STEM_MIN = 3
GENERIC_STEMS = {"__init__", "__main__", "index", "main", "utils", "common", "types", "conftest"}
JS_SYMBOL = re.compile(
    r"^\s{0,2}(?:export\s+)?(?:default\s+)?(?:async\s+)?"
    r"(?:function\*?\s+([A-Za-z_$][\w$]*)|class\s+([A-Za-z_$][\w$]*)"
    r"|(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:async\s*)?(?:function|\())"
)
COMMENT_LINE = re.compile(r"^\s*(?://+|/\*+|\*|#)\s?(.*?)\s*(?:\*/)?\s*$")


def tracked_files(root: Path) -> list[str]:
    done = subprocess.run(["git", "ls-files", "-z"], cwd=root, capture_output=True, check=False)
    if done.returncode != 0:
        raise SystemExit(f"gen_codemap: git ls-files failed: {done.stderr.decode().strip()}")
    return sorted(p for p in done.stdout.decode().split("\0") if Path(p).suffix in CODE_SUFFIXES)


def python_facts(text: str) -> tuple[str, list[str]]:
    tree = ast.parse(text)
    doc = (ast.get_docstring(tree) or "").strip().splitlines()
    names = [
        node.name for node in tree.body
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
        and not node.name.startswith("_")
    ]
    return (doc[0] if doc else ""), names


def comment_purpose(lines: list[str]) -> str:
    for line in lines[:8]:
        if line.startswith("#!") or not line.strip():
            continue
        match = COMMENT_LINE.match(line)
        if not match:
            return ""
        text = match.group(1).strip()
        if text and not text.startswith(("eslint", "@ts-", "shellcheck", "SPDX", "Copyright")):
            return text
    return ""


def script_facts(text: str) -> tuple[str, list[str]]:
    lines = text.splitlines()
    names = []
    for line in lines:
        match = JS_SYMBOL.match(line)
        if match:
            name = next(group for group in match.groups() if group)
            if not name.startswith("_") and name not in names:
                names.append(name)
    return comment_purpose(lines), names


def stem_key(path: str) -> str:
    return Path(path).stem.lower().replace("-", "_").removesuffix(".test").removesuffix(".spec")


def tests_for(path: str, tests: list[str]) -> list[str]:
    stem = stem_key(path)
    if len(stem) < STEM_MIN or stem in GENERIC_STEMS:
        return []
    return [t for t in tests if stem in stem_key(t)][:TESTS_MAX]


def entry(root: Path, path: str, tests: list[str]) -> str:
    text = (root / path).read_text(encoding="utf-8", errors="replace")
    try:
        purpose, names = (python_facts if path.endswith(".py") else script_facts)(text)
    except SyntaxError as err:
        raise SystemExit(f"gen_codemap: {path} does not parse on this Python: {err}") from err
    parts = [f"- `{Path(path).name}`", f" - {purpose.rstrip('.')}" if purpose else ""]
    if names:
        more = f" (+{len(names) - SYMBOLS_MAX} more)" if len(names) > SYMBOLS_MAX else ""
        parts.append(f" | symbols: {' '.join(names[:SYMBOLS_MAX])}{more}")
    owned = tests_for(path, tests)
    if owned:
        parts.append(f" | tests: {' '.join(owned)}")
    return "".join(parts)


def render(root: Path) -> str:
    files = tracked_files(root)
    tests = [p for p in files if p.startswith(TEST_PREFIXES)]
    by_dir = defaultdict(list)
    for path in files:
        if path.startswith(SOURCE_PREFIXES):
            by_dir[str(Path(path).parent)].append(path)
    out = [
        "# Code map",
        "",
        "@generated by `tools/gen_codemap.py` from the tracked files; CI fails when it is stale.",
        "Regenerate with `python3 tools/gen_codemap.py` after adding, moving or renaming code.",
        "Each line: file - purpose (module docstring or first comment) | symbols: public top-level",
        "names | tests: test files named after the module.",
        "",
    ]
    for folder in sorted(by_dir):
        out += [f"## {folder}/", ""]
        out += [entry(root, path, tests) for path in by_dir[folder]]
        out.append("")
    return "\n".join(out)


def check(root: Path) -> int:
    target = root / OUT
    current = target.read_text(encoding="utf-8") if target.exists() else ""
    if current != render(root):
        print(f"gen_codemap: {OUT} is stale; run python3 tools/gen_codemap.py and commit it")
        return 1
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        if args.check:
            return check(REPO_ROOT)
        (REPO_ROOT / OUT).write_text(render(REPO_ROOT), encoding="utf-8")
    except SystemExit as err:
        print(err, file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
